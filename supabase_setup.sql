-- 1) Creează mai întâi un utilizator în Supabase Dashboard > Authentication > Users.
-- 2) Înlocuiește admin@exemplu.ro de mai jos cu emailul acelui utilizator.
-- 3) Rulează tot acest fișier în SQL Editor.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'user' check (role in ('user', 'admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.tickets (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  message text not null,
  reply text not null default '',
  created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
alter table public.tickets enable row level security;

grant select on public.profiles to authenticated;
grant insert on public.tickets to anon, authenticated;
grant select, update, delete on public.tickets to authenticated;

drop policy if exists "Users can read own profile" on public.profiles;
create policy "Users can read own profile"
on public.profiles for select
to authenticated
using (id = auth.uid());

drop policy if exists "Anyone can submit a ticket" on public.tickets;
create policy "Anyone can submit a ticket"
on public.tickets for insert
to anon, authenticated
with check (
  char_length(trim(name)) between 1 and 100
  and char_length(trim(email)) between 3 and 254
  and char_length(trim(message)) between 1 and 5000
);

drop policy if exists "Admins can read tickets" on public.tickets;
create policy "Admins can read tickets"
on public.tickets for select
to authenticated
using (
  exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.role = 'admin'
  )
);

drop policy if exists "Admins can update tickets" on public.tickets;
create policy "Admins can update tickets"
on public.tickets for update
to authenticated
using (
  exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.role = 'admin'
  )
)
with check (
  exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.role = 'admin'
  )
);

drop policy if exists "Admins can delete tickets" on public.tickets;
create policy "Admins can delete tickets"
on public.tickets for delete
to authenticated
using (
  exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.role = 'admin'
  )
);

-- IMPORTANT: schimbă adresa de mai jos cu emailul administratorului creat la pasul 1.
insert into public.profiles (id, role)
select id, 'admin'
from auth.users
where lower(email) = lower('admin@exemplu.ro')
on conflict (id) do update set role = 'admin';

-- Verificare: această interogare trebuie să returneze un rând cu rolul admin.
select u.email, p.role
from auth.users u
join public.profiles p on p.id = u.id
where lower(u.email) = lower('admin@exemplu.ro');
